// Makes single-file copies for Supabase's browser editor. No dependencies required.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const shared = (await readFile(path.join(root,'supabase/functions/_shared/backend.ts'),'utf8')).replace(/^export /gm,'');
for (const name of ['create-payment','xendit-webhook','reconcile-payments','payment-return']) {
  const entry = (await readFile(path.join(root,'supabase/functions',name,'index.ts'),'utf8')).replace(/^import .*;\r?\n/gm,'');
  const folder = path.join(root,'supabase/dashboard',name);
  await mkdir(folder,{recursive:true});
  await writeFile(path.join(folder,'index.ts'),'// Generated by scripts/build-dashboard-functions.mjs; edit canonical source instead.\nexport {};\n'+shared+'\n'+entry);
  console.log('Generated supabase/dashboard/'+name+'/index.ts');
}
